# Create a distributable ZIP from a locally tested BepInEx plugin DLL.
# Run from the game's root folder (next to Normal Golf Game.exe).
param([string]$GameDir = (Get-Location).Path, [string]$Version = 'v0.9.0-beta')
$ErrorActionPreference = 'Stop'
$GameDir = (Resolve-Path -LiteralPath $GameDir).Path
$path = Join-Path $GameDir 'BepInEx\plugins\NormalGolfItalianI2.dll'
$folder = Join-Path $GameDir 'BepInEx\normal-golf-italian'
$translation = Join-Path $GameDir 'BepInEx\Translation\it\Text\ItalianoCompleto.txt'
$need = @($path, (Join-Path $folder 'i2_terms.tsv'), (Join-Path $folder 'ui_challenges.tsv'), $translation)
foreach ($file in $need) {
    if (-not (Test-Path -LiteralPath $file)) { throw "File mancante: $file" }
}
$stream = [System.IO.File]::OpenRead($path)
try {
    if ($stream.ReadByte() -ne 77 -or $stream.ReadByte() -ne 90) { throw 'DLL non valida (firma MZ mancante).' }
} finally { $stream.Dispose() }
$staging = Join-Path $env:TEMP ('normal-golf-it-packaging-' + [guid]::NewGuid().ToString('N'))
New-Item -ItemType Directory -Path $staging -Force | Out-Null
$files = @(
    @{Src=$path;Dest='BepInEx\plugins\NormalGolfItalianI2.dll'},
    @{Src=(Join-Path $folder 'i2_terms.tsv');Dest='BepInEx\normal-golf-italian\i2_terms.tsv'},
    @{Src=(Join-Path $folder 'ui_challenges.tsv');Dest='BepInEx\normal-golf-italian\ui_challenges.tsv'},
    @{Src=$translation;Dest='BepInEx\Translation\it\Text\ItalianoCompleto.txt'}
)
foreach ($item in $files) {
    $dest = Join-Path $staging $item.Dest
    New-Item -ItemType Directory -Path (Split-Path $dest -Parent) -Force | Out-Null
    Copy-Item -LiteralPath $item.Src -Destination $dest
}
$readme = @'
Normal Golf Game - Traduzione italiana (Beta sperimentale)
Requisiti: copia del gioco Windows, BepInEx 5 per Unity Mono, XUnity.AutoTranslator per BepInEx.
1. Chiudi il gioco e crea un backup di BepInEx/plugins/NormalGolfItalianI2.dll, se presente.
2. Estrai lo ZIP nella cartella di Normal Golf Game.exe, mantenendo le cartelle.
3. In BepInEx/config/AutoTranslatorConfig.ini imposta Language=it, FromLanguage=en,
   Endpoint= e FallbackEndpoint= (entrambi vuoti per funzionamento offline).
4. Se presenti, rinomina le vecchie patch ItalianoAnteprima.txt e conserva a parte
   _AutoGeneratedTranslations.txt, per non caricare vecchie traduzioni automatiche errate.
5. Avvia il gioco con English come lingua di origine.
Beta: non ancora convalidata con un playthrough completo.
Questa patch non include DLL o asset originali del videogioco.
'@
[System.IO.File]::WriteAllText((Join-Path $staging 'LEGGIMI.txt'),$readme,[System.Text.UTF8Encoding]::new($false))
$dist = Join-Path $GameDir 'dist'
New-Item -ItemType Directory -Path $dist -Force | Out-Null
$zip = Join-Path $dist ('NormalGolf_Italian_' + $Version + '.zip')
if (Test-Path -LiteralPath $zip) { Remove-Item -LiteralPath $zip -Force }
Compress-Archive -Path (Join-Path $staging '*') -DestinationPath $zip -CompressionLevel Optimal
Write-Host "PACCHETTO CREATO: $zip" -ForegroundColor Green
Get-FileHash -LiteralPath $zip -Algorithm SHA256 | Format-List
